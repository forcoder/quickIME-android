    private fun addEntry(pinyin: String, chars: String) {
        pinyinMap.getOrPut(pinyin) { mutableListOf() }.addAll(chars.toList().map { it.toString() })
    }

    /**
     * 根据拼音获取候选汉字
     */
    fun getCandidates(pinyin: String): List<String> {
        return pinyinMap[pinyin.lowercase()] ?: emptyList()
    }

    /**
     * 模糊匹配拼音
     */
    fun fuzzyMatch(query: String): List<Pair<String, List<String>>> {
        val results = mutableListOf<Pair<String, List<String>>>()
        val lowerQuery = query.lowercase()

        pinyinMap.entries.forEach { (pinyin, chars) ->
            if (pinyin.startsWith(lowerQuery) || fuzzyMatchPinyin(pinyin, lowerQuery)) {
                results.add(pinyin to chars)
            }
        }

        return results.sortedBy { it.first.length }
    }

    /**
     * 模糊匹配（支持简拼）
     */
    private fun fuzzyMatchPinyin(fullPinyin: String, query: String): Boolean {
        if (query.length >= fullPinyin.length) return false

        // 检查是否是简拼匹配
        val shortPinyin = PinyinUtil.getShortPinyin(fullPinyin)
        return shortPinyin.startsWith(query)
    }
